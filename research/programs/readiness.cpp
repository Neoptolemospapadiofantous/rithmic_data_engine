// 2026-10-28 readiness.cpp — applies docs/readiness_standard.md (v1) to every setup. Fed by scripts/readiness.sh, which writes the
// input TSV from the edge_lab full-history reports (gates R1, R3, R6, R7), the paper-fleet build map (R10) and the forward
// scorecard (R12); this program computes R2, R4, R5, R8, R9 and R11 from each setup's walk-forward trades and writes the scorecard.
// TSV columns (18, tab, header line, -1 = not run): id market sealed screen dir_pct time_pct day_pct need robust_ok late_ok plateau_ok
// confirm_ok built parity fwd_n fwd_avg fwd_pf wf_file
// Usage: readiness TSV OUTDIR  →  OUTDIR/scorecard.md + scorecard.csv. Thresholds are the standard's; change them only with a new
// version of the standard.
#include "research/meta.hpp"
#include <cstdio>
#include <fstream>
#include <map>
#include <random>
#include <sstream>
using namespace lab;
struct Tr { int date; double net, stop, atr; };
enum G { PASS, WARN, FAIL, PEND };
static const char* GS[4] = {"PASS", "WARN", "FAIL", "PENDING"};
int main(int argc, char** argv) {
  if (argc < 3) { fprintf(stderr, "usage: readiness TSV OUTDIR\n"); return 2; }
  double atrNow[2] = {0, 0};
  for (int m = 0; m < 2; ++m) { std::set<int> fomc; paper::VixRegime vix; vix.load("data/regime"); Series s; std::string err;
    if (!load_raw("data/edge_lab/cache", m ? "ES" : "NQ", s, err)) { fprintf(stderr, "%s\n", err.c_str()); return 1; } build_days(s, fomc, vix);
    for (int di = (int)s.days.size() - 1; di >= 0; --di) if (s.days[di].ok && s.days[di].atr > 0) { atrNow[m] = s.days[di].atr; break; } }
  const std::string out = argv[2];
  FILE* md = std::fopen((out + "/scorecard.md").c_str(), "w"); FILE* cs = std::fopen((out + "/scorecard.csv").c_str(), "w");
  if (!md || !cs) { fprintf(stderr, "cannot write %s\n", out.c_str()); return 1; }
  fprintf(cs, "id,market,level,R1,R2,R3,R4,R5,R6,R7,R8,R9,R10,R11,R12,wf_n,wf_pf,wf_exp_r,t,exp_r_11_15,exp_r_16_20,exp_r_21_24,years_pos,stress_pf,ho_n,ho_pf,ho_exp_r,stop_usd_micro,dd95_usd_micro,micros_50k,micros_150k,fwd_n\n");
  fprintf(md, "# Readiness scorecard — standard v1 (docs/readiness_standard.md)\n\nToday's ATR: NQ %.0f, ES %.1f pts. Generated by scripts/readiness.sh.\n\n", atrNow[0], atrNow[1]);
  fprintf(md, "| setup | mkt | level | R1 | R2 | R3 | R4 | R5 | R6 | R7 | R8 | R9 | R10 | R11 | R12 |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n");
  std::string detail;
  std::ifstream in(argv[1]); std::string line; std::getline(in, line);
  while (std::getline(in, line)) { if (line.empty()) continue;
    std::vector<std::string> c; std::stringstream ss(line); std::string x; while (std::getline(ss, x, '\t')) c.push_back(x);
    if (c.size() < 18) { fprintf(stderr, "bad row: %s\n", line.c_str()); return 1; }
    auto num = [&](int i) { return std::atof(c[i].c_str()); };
    const std::string id = c[0], mkt = c[1]; const int m = mkt == "ES"; const bool sealed = num(2) > 0;
    const double cost = m ? 0.5 : 1.5, stress = m ? 1.0 : 3.5, pvMicro = m ? 5 : 2;
    std::vector<Tr> tr; { std::ifstream f(c[17]); if (!f) { fprintf(stderr, "missing %s\n", c[17].c_str()); return 1; } std::string r; std::getline(f, r);
      const bool wave = r.rfind("date,et_hhmm", 0) == 0;
      while (std::getline(f, r)) { std::vector<std::string> v; std::stringstream rs(r); std::string y; while (std::getline(rs, y, ',')) v.push_back(y);
        Tr t{}; t.date = std::atoi(v[0].c_str());
        if (wave) { t.net = std::atof(v[5].c_str()) - cost; t.stop = std::atof(v[4].c_str()); t.atr = std::atof(v[7].c_str()); }
        else { t.net = std::atof(v[5].c_str()); t.stop = std::atof(v[9].c_str()); t.atr = std::atof(v[10].c_str()); }
        if (t.atr > 0 && t.date >= 20110701 && t.date <= 20261023) tr.push_back(t); } }
    int zero = 0; for (auto& t : tr) zero += !(t.stop > 0); const bool nostop = zero > (int)tr.size() / 2;
    auto Rof = [&](const Tr& t) { return nostop || !(t.stop > 0) ? 0.5 * t.atr : t.stop; };
    struct St { double n = 0, sr = 0, gw = 0, gl = 0, s = 0, s2 = 0, gws = 0, gls = 0; };
    auto stat = [&](int a, int b) { St st; for (auto& t : tr) if (t.date >= a && t.date <= b) { const double r = t.net / Rof(t), z = t.net / t.atr, zs = (t.net - (stress - cost)) / t.atr;
        st.n++; st.sr += r; (z > 0 ? st.gw : st.gl) += std::fabs(z); st.s += z; st.s2 += z * z; (zs > 0 ? st.gws : st.gls) += std::fabs(zs); } return st; };
    auto pf = [](double w, double l) { return l > 0 ? w / l : 99.0; };
    const St wf = stat(20110701, 20241231), p0 = stat(20110701, 20151231), p1 = stat(20160101, 20201231), p2 = stat(20210101, 20241231), ho = stat(20250101, 20261023);
    const double wfExp = wf.n ? wf.sr / wf.n : 0, mean = wf.n ? wf.s / wf.n : 0, sd = wf.n > 1 ? std::sqrt(std::max(0.0, wf.s2 / wf.n - mean * mean)) : 0;
    const double t = sd > 0 ? mean / sd * std::sqrt(wf.n) : 0;
    std::map<int, double> yr; for (auto& q : tr) if (q.date <= 20241231) yr[q.date / 10000] += q.net / q.atr; int yp = 0; for (auto& [y, v] : yr) yp += v > 0;
    const double e0 = p0.n ? p0.sr / p0.n : 0, e1 = p1.n ? p1.sr / p1.n : 0, e2 = p2.n ? p2.sr / p2.n : 0, hoExp = ho.n ? ho.sr / ho.n : 0;
    // R11: today's stop on 1 micro; bootstrap of the setup's own trading days 2016-26 (1 micro, today's size), 252-day paths
    double stopAtr = 0; int ns = 0; for (auto& q : tr) if (q.date >= 20160101) { stopAtr += Rof(q) / q.atr; ++ns; } stopAtr = ns ? stopAtr / ns : 0;
    const double stopUsd = stopAtr * atrNow[m] * pvMicro;
    std::map<int, double> dayUsd; for (auto& q : tr) if (q.date >= 20160101) dayUsd[q.date] += q.net / q.atr * atrNow[m] * pvMicro;
    std::vector<double> dv; for (auto& [d, v] : dayUsd) dv.push_back(v);
    // days with a trade per year → each simulated year draws that many trade days (the rest are flat days and do not move equity)
    const double perYear = dv.size() / 10.8; std::vector<double> dds; std::mt19937 rng(20261028);
    for (int sim = 0; sim < 2000 && !dv.empty(); ++sim) { double eq = 0, pk = 0, dd = 0; const int k = (int)std::lround(perYear);
      for (int j = 0; j < k; ++j) { eq += dv[rng() % dv.size()]; pk = std::max(pk, eq); dd = std::max(dd, pk - eq); } dds.push_back(dd); }
    std::sort(dds.begin(), dds.end()); const double dd95 = dds.empty() ? 0 : dds[(size_t)(0.95 * (dds.size() - 1))];
    auto fit = [&](double allow) { if (!(stopUsd > 0) || !(dd95 > 0)) return 0; return (int)std::min(std::floor(0.2 * allow / stopUsd), std::floor(0.5 * allow / dd95)); };
    const int f50 = fit(2000), f150 = fit(4500);
    // gates
    G g[12];
    g[0] = num(3) < 0 ? FAIL : num(3) > 0 ? PASS : FAIL;
    g[1] = wf.n >= 150 && pf(wf.gw, wf.gl) >= 1.15 && wfExp >= 0.08 ? PASS : FAIL;
    { const double need = num(7); if (num(4) < 0) g[2] = FAIL; else if (num(4) < need) g[2] = FAIL; else if (num(5) >= need) g[2] = PASS; else if (num(6) >= need) g[2] = WARN; else g[2] = FAIL; }
    g[3] = e1 > 0 && e2 > 0 && e0 > -0.05 && yr.size() && yp >= 0.6 * yr.size() ? PASS : FAIL;
    g[4] = wf.gws > wf.gls && pf(wf.gws, wf.gls) >= 1.05 ? PASS : FAIL;
    g[5] = num(11) > 0 ? PASS : FAIL;
    g[6] = num(8) < 0 ? FAIL : num(8) == 0 ? FAIL : (num(9) > 0 && num(10) > 0) ? PASS : WARN;
    g[7] = ho.n < 30 ? (ho.n > 0 && ho.s <= 0 ? FAIL : WARN) : ho.s > 0 ? PASS : FAIL;
    g[8] = t >= 3.0 ? PASS : t >= 2.5 ? WARN : FAIL;
    g[9] = num(12) <= 0 ? FAIL : num(13) > 0 ? PASS : WARN;
    g[10] = f150 >= 1 ? PASS : FAIL;
    g[11] = num(14) < 40 ? PEND : (num(15) > 0 && num(16) >= 1.1) ? PASS : FAIL;
    bool research = true; for (int k = 0; k < 9; ++k) research &= g[k] != FAIL;
    const char* level = !research ? "NOT READY" : g[9] != PASS ? "RESEARCH-READY" : (g[10] == PASS && g[11] == PASS) ? "LIVE-READY" : "BUILD-READY";
    fprintf(md, "| %s | %s | **%s** |", id.c_str(), mkt.c_str(), level);
    for (int k = 0; k < 12; ++k) fprintf(md, " %s%s |", GS[g[k]], k == 7 && g[k] == PASS ? (sealed ? " sealed" : " seen") : "");
    fprintf(md, "\n");
    char buf[2048];
    std::snprintf(buf, sizeof buf, "- **%s** (%s%s): walk-forward 2011-24 n %.0f, PF %.2f, %+.3f R/trade, t %.1f · periods %+.3f / %+.3f / %+.3f R, %d/%zu years + · live-cost PF %.2f · "
                  "holdout n %.0f, PF %.2f, %+.3f R · controls dir %.2f time %.2f day %.2f (need %.2f) · stop on 1 micro today $%.0f, 95%% one-year drawdown $%.0f → micros: 50K %d, 150K %d%s · forward %.0f trades\n",
                  id.c_str(), mkt.c_str(), nostop ? ", no stop — 1 R = 0.5 ATR" : "", wf.n, pf(wf.gw, wf.gl), wfExp, t, e0, e1, e2, yp, yr.size(), pf(wf.gws, wf.gls),
                  ho.n, pf(ho.gw, ho.gl), hoExp, num(4), num(5), num(6), num(7), stopUsd, dd95, f50, f150, num(12) > 0 ? "" : " · NOT BUILT", num(14));
    detail += buf;
    fprintf(cs, "%s,%s,%s", id.c_str(), mkt.c_str(), level); for (int k = 0; k < 12; ++k) fprintf(cs, ",%s", GS[g[k]]);
    fprintf(cs, ",%.0f,%.3f,%.4f,%.2f,%.4f,%.4f,%.4f,%d,%.3f,%.0f,%.3f,%.4f,%.0f,%.0f,%d,%d,%.0f\n", wf.n, pf(wf.gw, wf.gl), wfExp, t, e0, e1, e2, yp, pf(wf.gws, wf.gls), ho.n, pf(ho.gw, ho.gl), hoExp, stopUsd, dd95, f50, f150, num(14)); }
  fprintf(md, "\n## Numbers behind each line\n\n%s", detail.c_str());
  std::fclose(md); std::fclose(cs); return 0;
}
